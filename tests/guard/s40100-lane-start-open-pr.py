def lop_cost_check(step, want_calls):
    """Cost of an allowed start: the gh reads it makes, no gh child process, no sleep and no file written. The control
    (no step tag) holds the same claims on today's guard, so the file claim is not carried by something else."""
    def check():
        run = lop_run(LANE_TOOL, lop_input(prompt=CITE_NUM, step=step), LANE_REPO, lop_gh([PR_2767]))
        ok, message = lop_check(run, want_calls, "allow")
        if not ok:
            return False, message
        gh_children = [child for child in run["children"] if child.lstrip("[").lstrip("'\"").startswith("gh")]
        if gh_children:
            return False, "a gh child process started outside the seam: %s" % gh_children[:2]
        if run["sleeps"]:
            return False, "%d sleep(s) in the judge, want none" % run["sleeps"]
        if run["files"]:
            return False, "%d file(s) written by an allowed start, want none: %s" % (len(run["files"]), run["files"][:2])
        return True, "%d gh read(s), no gh child, no sleep, no file" % len(run["calls"])
    return check


LOG_CHECKS_EXTRA.append(("lane-start-open-pr: a start with no step tag reads no gh, writes no file, sleeps not",
                         lop_cost_check(step=False, want_calls=0)))
LOG_CHECKS_EXTRA.append(("lane-start-open-pr: a judged start reads gh once, writes no file, sleeps not",
                         lop_cost_check(step=True, want_calls=1)))
