#!/usr/bin/env python3
"""Cases for the guard's protected-path rule: a file or folder a repo lists as one a session may not write.

    python3 hooks/test_guard_protected.py
    python3 -m pytest hooks/test_guard_protected.py -q

A repo lists its protected paths in its layout extras file, under "protected-paths":
[{"path": "fixtures/", "why": "..."}]. A trailing slash names a folder, and any other path names one file.
The list read is that of the checkout holding the target, never the cwd's. A Write, Edit, MultiEdit or
NotebookEdit to a protected path is denied, and so is a shell write to one, or an interpreter's write. A read,
a copy out, or a name inside quotes is allowed.

GUARD_UNDER_TEST points the cases at another copy of the guard, so a mutant of the built rule runs the same
cases. Each case drives the guard as Claude Code does: one JSON object on stdin, the decision read off stdout.
Each test has a config folder of its own, so its guard.log is its own.

Each allow case first shows the rule live on a protected write in its own repo. Scope before subject (P7):
a missing rule fails that control, so an allow never passes by accident.
"""
import json
import os
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
GUARD = os.environ.get("GUARD_UNDER_TEST") or os.path.join(HERE, "guard.py")
sys.path.insert(0, os.path.join(HERE, "..", "lint"))
sys.path.insert(0, os.path.join(HERE, "..", "testing"))
import _test_git  # noqa: E402,F401  test-run signing opt-out (lint/_test_git.py)
import _test_temp  # noqa: E402  test-temp-standard: every temp path comes from this run's folder
import tracked_tree  # noqa: E402  rm_tree also clears the read-only files git writes (testing/tracked_tree.py)

RUN_FOLDER = _test_temp.run_folder()  # test-temp-standard: one run folder per test run, removed at teardown
RULE = "protected-path"
EXTRAS_REL = ".claude/layout-extras.json"
WHY = "generated by make fixtures; edit the generator, not the file"
WHY_FILE = "the changelog is written by the release script"
ENTRIES = [{"path": "fixtures/", "why": WHY}, {"path": "docs/CHANGELOG.md", "why": WHY_FILE}]
PY_HEREDOC = "python3 - <<'EOF'\nopen('fixtures/a', 'w').write('x')\nEOF"
NODE_HEREDOC = ("node - <<'EOF'\nconst note = `\n// fixtures/a is generated\n`;\n"
                "require('fs').writeFileSync('fixtures/a', note);\nEOF")

# Counts the opens of the extras file the guard makes. Both open functions are wrapped, builtins.open and io.open,
# so a read through pathlib counts too. The probe runs the guard in place, so the guard's own reads are what it sees.
OPEN_PROBE = r"""
import builtins, io, os, runpy, sys
guard, log, target = sys.argv[1], sys.argv[2], sys.argv[3]
sys.path.insert(0, os.path.dirname(guard))
real = builtins.open
def counting(file, *args, **kwargs):
    if isinstance(file, (str, bytes, os.PathLike)) and os.fsdecode(file).replace("\\", "/").endswith(target):
        with real(log, "a", encoding="utf-8") as handle:
            handle.write(os.fsdecode(file) + "\n")
    return real(file, *args, **kwargs)
builtins.open = counting
io.open = counting
sys.argv = [guard]
runpy.run_path(guard, run_name="__main__")
"""


def tearDownModule():
    tracked_tree.rm_tree(RUN_FOLDER)


def keyed_text(entries=ENTRIES):
    return json.dumps({"kinds": {}, "protected-paths": entries})


def keyless_text():
    return json.dumps({"kinds": {}})


def list_only_text(entries=ENTRIES):
    """An extras file that holds the protected-paths key and no "kinds" beside it."""
    return json.dumps({"protected-paths": entries})


def git(cwd, *args):
    subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True)


def write_file(root, rel, text):
    path = os.path.join(root, *rel.split("/"))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def make_repo(root, extras):
    """A git checkout at `root` with fixtures/a.csv and src/app.py. Its extras file is `extras` as given, none when None."""
    os.makedirs(root)
    git(root, "init", "-q", "-b", "main", ".")
    write_file(root, "fixtures/a.csv", "a\n")
    write_file(root, "src/app.py", "x = 1\n")
    if extras is not None:
        write_file(root, EXTRAS_REL, extras)
    git(root, "add", "-A")
    git(root, "-c", "user.name=test", "-c", "user.email=test@example.invalid", "commit", "-q", "-m", "first")
    return root


def tool_body(tool, path, cwd):
    """The payload of one write tool call on `path`, judged from `cwd`, in Claude Code's shape."""
    if tool == "NotebookEdit":
        tool_input = {"notebook_path": path, "new_source": "x", "edit_mode": "replace"}
    elif tool == "MultiEdit":
        tool_input = {"file_path": path, "edits": [{"old_string": "a", "new_string": "b"}]}
    elif tool == "Edit":
        tool_input = {"file_path": path, "old_string": "a", "new_string": "b"}
    else:
        tool_input = {"file_path": path, "content": "x"}
    return {"tool_name": tool, "tool_input": tool_input, "cwd": cwd}


def shell_body(command, cwd):
    return {"tool_name": "Bash", "tool_input": {"command": command}, "cwd": cwd}


def describe(body):
    tool_input = body.get("tool_input") or {}
    shown = (tool_input.get("command") or tool_input.get("file_path") or tool_input.get("notebook_path")
             or body.get("hook_event_name", ""))
    return "%s %s" % (body.get("tool_name", ""), shown)


def read_decision(stdout):
    """(decision, reason) of one guard run. Empty output is an allow."""
    text = stdout.strip()
    if not text:
        return "allow", ""
    block = json.loads(text)["hookSpecificOutput"]
    return block["permissionDecision"], block["permissionDecisionReason"]


class Guarded(unittest.TestCase):
    """One tree per test: a repo `self.repo` that lists fixtures/ and docs/CHANGELOG.md, and its own config folder."""

    def setUp(self):
        self.tree = tempfile.mkdtemp(prefix="protected_", dir=RUN_FOLDER)
        self.addCleanup(tracked_tree.rm_tree, self.tree)
        self.cfg = os.path.join(self.tree, "cfg")
        os.makedirs(self.cfg)
        self.repo = self.make_repo("repo", keyed_text())

    def make_repo(self, name, extras):
        return make_repo(os.path.join(self.tree, name), extras)

    def at(self, rel, repo=None):
        return os.path.join(repo or self.repo, *rel.split("/"))

    def write(self, rel, repo=None, cwd=None, tool="Write"):
        base = repo or self.repo
        return tool_body(tool, self.at(rel, base), cwd or base)

    def shell(self, command, cwd=None):
        return shell_body(command, cwd or self.repo)

    def link(self, rel, target):
        path = self.at(rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        try:
            os.symlink(target, path)
        except OSError as err:
            self.skipTest("this machine cannot make a symlink: %s" % err)
        return path

    def env(self):
        env = dict(os.environ, CLAUDE_CONFIG_DIR=self.cfg, CLAUDE_GUARD_ROOT_PID=str(os.getpid()),
                   TMPDIR=RUN_FOLDER, TEMP=RUN_FOLDER, TMP=RUN_FOLDER)
        for name in ("CLAUDE_CODE_REMOTE", "CLAUDE_CODE_SESSION_ID", "CLAUDE_CODE_REMOTE_SESSION_ID",
                     "CLAUDE_PROJECT_DIR"):
            env.pop(name, None)
        return env

    def guard(self, body):
        """(decision, reason) of one guard run on `body`. A crash fails the case by name, so no red is a crash."""
        got = subprocess.run([sys.executable, GUARD], input=json.dumps(body), capture_output=True, text=True,
                             env=self.env(), timeout=120)
        if got.returncode:
            self.fail("the guard crashed (exit %d) on %s: %s" % (got.returncode, describe(body), got.stderr.strip()[-300:]))
        try:
            return read_decision(got.stdout)
        except (ValueError, KeyError) as err:
            self.fail("the guard printed no decision Claude Code can read on %s: %s" % (describe(body), err))

    def assertDenied(self, body, label):
        decision, reason = self.guard(body)
        self.assertEqual(decision, "deny", "%s: want deny, got %s: %s" % (label, decision, reason[:200]))
        self.assertTrue(reason.startswith(RULE + ": "), "%s: the deny names another rule: %s" % (label, reason[:200]))
        return reason

    def assertAllowed(self, body, label):
        decision, reason = self.guard(body)
        self.assertEqual(decision, "allow", "%s: want allow, got %s: %s" % (label, decision, reason[:200]))

    def assertDeniedBy(self, body, rule, label):
        """The guard denies `body`, and the deny names `rule`, so a control shows which rule is live."""
        decision, reason = self.guard(body)
        self.assertEqual(decision, "deny", "%s: want deny, got %s: %s" % (label, decision, reason[:200]))
        self.assertTrue(reason.startswith(rule + ": "), "%s: the deny names another rule: %s" % (label, reason[:200]))

    def assertLive(self):
        """Scope before subject: a protected write in this repo is denied by protected-path, so the rule is live here."""
        self.assertDenied(self.write("fixtures/a.csv"), "scope control: a Write to fixtures/a.csv in the keyed repo")

    def log_rows(self):
        path = os.path.join(self.cfg, "guard.log")
        if not os.path.exists(path):
            return []
        with open(path, encoding="utf-8") as handle:
            return [line.split("\t") for line in handle.read().splitlines() if line.strip()]

    def extras_opens(self, body):
        """How many times the guard opens the extras file on `body`, counted by OPEN_PROBE."""
        log = os.path.join(self.tree, "opens.log")
        if os.path.exists(log):
            os.remove(log)
        got = subprocess.run([sys.executable, "-c", OPEN_PROBE, GUARD, log, EXTRAS_REL], input=json.dumps(body),
                             capture_output=True, text=True, env=self.env(), timeout=120)
        if got.returncode:
            self.fail("the guard crashed (exit %d) under the open counter on %s: %s"
                      % (got.returncode, describe(body), got.stderr.strip()[-300:]))
        if not os.path.exists(log):
            return 0
        with open(log, encoding="utf-8") as handle:
            return len(handle.read().splitlines())


class Denies(Guarded):
    """A write to a protected path is denied through each write tool, and through each shell and interpreter form."""

    def test_a_write_to_a_protected_file_is_denied(self):
        self.assertDenied(tool_body("Write", "fixtures/a.csv", self.repo), "Write fixtures/a.csv by relative path")

    def test_an_edit_to_a_protected_file_is_denied(self):
        self.assertDenied(self.write("fixtures/a.csv", tool="Edit"), "Edit fixtures/a.csv")

    def test_a_multiedit_to_a_protected_file_is_denied(self):
        self.assertDenied(self.write("fixtures/a.csv", tool="MultiEdit"), "MultiEdit fixtures/a.csv")

    def test_a_notebookedit_to_a_protected_path_is_denied(self):
        self.assertDenied(self.write("fixtures/n.ipynb", tool="NotebookEdit"), "NotebookEdit fixtures/n.ipynb")

    def test_a_write_to_a_nested_file_under_a_protected_folder_is_denied(self):
        self.assertDenied(self.write("fixtures/x/y.csv"), "Write fixtures/x/y.csv")

    def test_a_write_by_absolute_path_is_denied(self):
        self.assertDenied(self.write("fixtures/a.csv"), "Write of the absolute path of fixtures/a.csv")

    def test_a_write_spelled_with_backslashes_is_denied(self):
        self.assertDenied(tool_body("Write", "fixtures\\a.csv", self.repo), "Write fixtures\\a.csv")

    def test_a_write_through_a_symlink_into_the_folder_is_denied(self):
        self.link("link.csv", self.at("fixtures/a.csv"))
        self.assertDenied(self.write("link.csv"), "Write to link.csv, a symlink to fixtures/a.csv")

    def test_a_write_to_a_link_spelled_under_the_folder_is_denied(self):
        self.link("fixtures/out.csv", os.path.join(self.tree, "outside.csv"))
        self.assertDenied(self.write("fixtures/out.csv"),
                          "Write to fixtures/out.csv, a symlink that points out of the repo")

    def test_a_redirect_over_a_protected_file_is_denied(self):
        self.assertDenied(self.shell("echo x > fixtures/a"), "echo x > fixtures/a")

    def test_an_append_to_a_protected_file_is_denied(self):
        self.assertDenied(self.shell("echo x >> fixtures/a"), "echo x >> fixtures/a")

    def test_tee_into_a_protected_file_is_denied(self):
        self.assertDenied(self.shell("echo x | tee fixtures/a"), "echo x | tee fixtures/a")

    def test_sed_in_place_on_a_protected_file_is_denied(self):
        self.assertDenied(self.shell("sed -i s/a/b/ fixtures/a"), "sed -i s/a/b/ fixtures/a")

    def test_rm_of_a_protected_file_is_denied(self):
        self.assertDenied(self.shell("rm fixtures/a"), "rm fixtures/a")

    def test_mv_into_the_folder_is_denied(self):
        self.assertDenied(self.shell("mv x fixtures/a"), "mv x fixtures/a")

    def test_mv_out_of_the_folder_is_denied(self):
        self.assertDenied(self.shell("mv fixtures/a x"), "mv fixtures/a x")

    def test_cp_into_the_folder_is_denied(self):
        self.assertDenied(self.shell("cp x fixtures/a"), "cp x fixtures/a")

    def test_cd_into_the_folder_then_touch_is_denied(self):
        self.assertDenied(self.shell("cd fixtures && touch a"), "cd fixtures && touch a")

    def test_a_python_heredoc_write_into_the_folder_is_denied(self):
        self.assertDenied(self.shell(PY_HEREDOC), "a python heredoc that opens fixtures/a for writing")

    def test_a_node_heredoc_write_after_a_multiline_template_literal_is_denied(self):
        self.assertDenied(self.shell(NODE_HEREDOC), "a node heredoc that writes fixtures/a after a multi-line template")

    def test_a_write_from_one_repo_into_a_protected_folder_of_another_is_denied(self):
        plain = self.make_repo("plain", keyless_text())
        self.assertLive()
        self.assertDenied(self.write("fixtures/a.csv", cwd=plain), "Write into the keyed repo's fixtures/, cwd in the keyless repo")

    def test_a_file_entry_protects_that_file_and_no_sibling(self):
        self.assertDenied(self.write("docs/CHANGELOG.md"), "Write to the file entry docs/CHANGELOG.md")
        self.assertAllowed(self.write("docs/CHANGELOG.md.bak"), "Write to docs/CHANGELOG.md.bak, a sibling of the entry")

    def test_the_refusal_quotes_the_why_of_the_entry_it_matched(self):
        reason = self.assertDenied(self.write("fixtures/a.csv"), "Write under fixtures/")
        self.assertIn(WHY, reason, "the deny for fixtures/ does not quote its why: %s" % reason[:200])
        reason = self.assertDenied(self.write("docs/CHANGELOG.md"), "Write to docs/CHANGELOG.md")
        self.assertIn(WHY_FILE, reason, "the deny for docs/CHANGELOG.md does not quote its why: %s" % reason[:200])
        self.assertNotIn(WHY, reason, "the deny for docs/CHANGELOG.md quotes the other entry's why")

    def test_a_long_list_protects_its_last_entry(self):
        entries = [{"path": "gen%02d/" % n, "why": "generated batch %d" % n} for n in range(50)]
        long_repo = self.make_repo("long", keyed_text(entries))
        self.assertDenied(self.write("gen49/x.csv", repo=long_repo), "Write under gen49/, the last of 50 entries")


class Allows(Guarded):
    """A read, a copy out, a lookalike path and a repo that does not list the path are allowed, each under a live control."""

    def test_reading_a_protected_file_is_allowed(self):
        self.assertLive()
        self.assertAllowed(self.shell("cat fixtures/a.csv"), "cat fixtures/a.csv")

    def test_grep_of_a_protected_file_is_allowed(self):
        self.assertLive()
        self.assertAllowed(self.shell("grep x fixtures/a.csv"), "grep x fixtures/a.csv")

    def test_echo_naming_a_protected_file_is_allowed(self):
        self.assertLive()
        self.assertAllowed(self.shell("echo fixtures/a.csv"), "echo fixtures/a.csv")

    def test_copying_a_protected_file_out_is_allowed(self):
        self.assertLive()
        out = os.path.join(self.tree, "out.csv")
        self.assertAllowed(self.shell("cp fixtures/a.csv %s" % out), "cp fixtures/a.csv out of the repo")

    def test_a_write_to_a_folder_with_the_same_prefix_is_allowed(self):
        self.assertLive()
        self.assertAllowed(self.write("fixturesX/a"), "Write fixturesX/a")

    def test_a_write_to_a_file_named_like_the_folder_is_allowed(self):
        self.assertLive()
        self.assertAllowed(self.write("src/fixtures.py"), "Write src/fixtures.py")

    def test_a_repo_with_no_key_allows_writes_to_its_fixtures(self):
        self.assertLive()
        plain = self.make_repo("plain", keyless_text())
        self.assertAllowed(self.write("fixtures/a.csv", repo=plain), "Write fixtures/a.csv in the keyless repo")

    def test_a_repo_with_no_extras_file_allows_writes_to_its_fixtures(self):
        self.assertLive()
        bare = self.make_repo("bare", None)
        self.assertAllowed(self.write("fixtures/a.csv", repo=bare), "Write fixtures/a.csv in the repo with no extras file")

    def test_a_write_into_another_repos_folder_is_judged_by_that_repo(self):
        self.assertLive()
        plain = self.make_repo("plain", keyless_text())
        self.assertAllowed(self.write("fixtures/a.csv", repo=plain, cwd=self.repo),
                           "Write into the keyless repo's fixtures/, cwd in the keyed repo")

    def test_an_empty_protected_list_protects_nothing(self):
        self.assertLive()
        empty = self.make_repo("empty", keyed_text([]))
        self.assertAllowed(self.write("fixtures/a.csv", repo=empty), "Write fixtures/a.csv under an empty list")


class Scanner(Guarded):
    """The shell reader respects quotes: a comment opener or an apostrophe inside quotes is text, not a comment or a quote."""

    def test_a_hash_inside_double_quotes_is_text_so_the_write_out_is_allowed(self):
        self.assertLive()
        self.assertAllowed(self.shell('echo "# fixtures/a" > out.txt'), 'echo "# fixtures/a" > out.txt')

    def test_a_double_slash_inside_double_quotes_is_text_so_the_write_out_is_allowed(self):
        self.assertLive()
        self.assertAllowed(self.shell('echo "// fixtures/a" > out.txt'), 'echo "// fixtures/a" > out.txt')

    def test_a_slash_star_inside_double_quotes_is_text_so_the_write_out_is_allowed(self):
        self.assertLive()
        self.assertAllowed(self.shell('echo "/* fixtures/a" > out.txt'), 'echo "/* fixtures/a" > out.txt')

    def test_adjacent_single_quotes_do_not_hide_the_redirect(self):
        self.assertDenied(self.shell("echo 'it''s' > fixtures/a"), "echo 'it''s' > fixtures/a")

    def test_a_lone_apostrophe_in_double_quotes_does_not_hide_the_redirect(self):
        self.assertDenied(self.shell("echo \"Don't\" > fixtures/a"), "echo \"Don't\" > fixtures/a")

    def test_a_multiline_quoted_string_does_not_hide_the_redirect(self):
        self.assertDenied(self.shell('echo "line one\n# line two\nline three" > fixtures/a'),
                          "a double-quoted string over three lines, then > fixtures/a")


class Malformed(Guarded):
    """A malformed protected key fails open, and says so once in guard.log."""

    def test_a_malformed_protected_key_fails_open(self):
        self.assertLive()
        bad = self.make_repo("bad", json.dumps({"kinds": {}, "protected-paths": "fixtures/"}))
        self.assertAllowed(self.write("fixtures/a.csv", repo=bad), "Write fixtures/a.csv in the malformed repo")

    def test_a_malformed_protected_key_logs_one_noted_line(self):
        self.assertLive()
        bad = self.make_repo("bad", json.dumps({"kinds": {}, "protected-paths": "fixtures/"}))
        self.assertAllowed(self.write("fixtures/a.csv", repo=bad), "Write fixtures/a.csv in the malformed repo")
        noted = [row for row in self.log_rows() if len(row) > 3 and row[2] == "noted" and row[3] == RULE]
        self.assertEqual(len(noted), 1, "want one noted %s line in guard.log, got %d: %r"
                         % (RULE, len(noted), self.log_rows()))


class Cost(Guarded):
    """The extras file is read only for a call that looks like a write: a read-only Bash call opens it not at all."""

    def test_a_read_only_bash_call_does_not_open_the_extras_file(self):
        control = self.extras_opens(self.shell("echo x > out.txt"))
        self.assertGreaterEqual(control, 1, "control: a write-looking Bash call opened the extras file %d times, want at "
                                            "least 1, so the rule does not read the file for a write" % control)
        opened = self.extras_opens(self.shell("ls"))
        self.assertEqual(opened, 0, "a read-only ls opened the extras file %d times, want 0" % opened)

    def test_a_repo_with_no_key_opens_its_extras_file_at_most_once(self):
        control = self.extras_opens(self.shell("echo x > out.txt"))
        self.assertGreaterEqual(control, 1, "control: a write-looking Bash call opened the extras file %d times, want at "
                                            "least 1, so the rule does not read the file for a write" % control)
        plain = self.make_repo("plain", keyless_text())
        opened = self.extras_opens(self.shell("echo x > out.txt", cwd=plain))
        self.assertLessEqual(opened, 1, "a repo with no protected key opened its extras file %d times, want at most 1"
                             % opened)


